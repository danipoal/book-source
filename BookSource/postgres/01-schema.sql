-- BookSource - esquema PostgreSQL (portado desde sqlserver/init.sql)
-- Se ejecuta automaticamente al crear el volumen por primera vez
-- (/docker-entrypoint-initdb.d en la imagen oficial de postgres).
--
-- Notas de la migracion:
--  * SQL Server comparaba texto sin distinguir mayusculas; en PostgreSQL se
--    mantiene ese comportamiento usando citext en las columnas que se buscan.
--  * Los identificadores van sin comillas (se guardan en minusculas); la app
--    los lee sin distinguir mayusculas, asi que no hace falta tocar los modelos.
--  * La tabla User se llama "user" (palabra reservada): hay que citarla.

CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE book (
    idbook      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       citext  NOT NULL,
    author      citext  NOT NULL,
    description varchar(5000),
    imageurl    varchar(255),
    subtitle    varchar(255),
    editorial   citext,
    pagecount   integer,
    score       double precision
);

CREATE TABLE category (
    idcategory   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoryname citext  NOT NULL UNIQUE
);

CREATE TABLE "user" (
    iduser          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        citext  NOT NULL UNIQUE,
    email           citext  NOT NULL UNIQUE,
    passwordhash    bytea   NOT NULL,
    passwordsalt    bytea   NOT NULL,
    birthdate       date,
    profileimageurl varchar(255)
);

CREATE TABLE book_category (
    fkidcategory integer NOT NULL REFERENCES category (idcategory),
    fkidbook     integer NOT NULL REFERENCES book (idbook),
    PRIMARY KEY (fkidcategory, fkidbook)
);

CREATE TABLE follow (
    fkidfollower integer NOT NULL REFERENCES "user" (iduser),
    fkidfollowed integer NOT NULL REFERENCES "user" (iduser),
    PRIMARY KEY (fkidfollower, fkidfollowed)
);

CREATE TABLE listofbooks (
    idlistofbooks integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listname      varchar(255) NOT NULL,
    fkiduser      integer      NOT NULL REFERENCES "user" (iduser)
);

CREATE TABLE listofbooks_book (
    fkidlistofbooks integer NOT NULL REFERENCES listofbooks (idlistofbooks),
    fkidbook        integer NOT NULL REFERENCES book (idbook),
    PRIMARY KEY (fkidlistofbooks, fkidbook)
);

CREATE TABLE publication (
    idpublication integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         varchar(255) NOT NULL,
    content       varchar(255) NOT NULL,
    pubimage      varchar(255),
    fkiduser      integer      NOT NULL REFERENCES "user" (iduser)
);

CREATE TABLE publicationlikes (
    fkiduser        integer NOT NULL REFERENCES "user" (iduser),
    fkidpublication integer NOT NULL REFERENCES publication (idpublication),
    PRIMARY KEY (fkiduser, fkidpublication)
);

CREATE TABLE review (
    idreview integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comment  varchar(512) NOT NULL,
    fkidbook integer      NOT NULL REFERENCES book (idbook),
    fkiduser integer      NOT NULL REFERENCES "user" (iduser)
);
